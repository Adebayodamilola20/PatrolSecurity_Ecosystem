import { v4 as uuidv4 } from 'uuid'
import db from '../db.js'
import { sendNotificationBundle } from './notifications.js'

function getSettingValue(settings, key, fallback = '') {
  const row = settings.find(s => s.settingKey === key || s.settingkey === key)
  return row?.settingValue ?? row?.settingvalue ?? fallback
}

function getDateRange(rangeType) {
  const now = new Date()
  let start, end

  switch (rangeType) {
    case 'today': {
      start = new Date(now.getFullYear(), now.getMonth(), now.getDate()).toISOString()
      end = now.toISOString()
      break
    }
    case 'yesterday': {
      const yesterday = new Date(now)
      yesterday.setDate(yesterday.getDate() - 1)
      start = new Date(yesterday.getFullYear(), yesterday.getMonth(), yesterday.getDate()).toISOString()
      end = new Date(now.getFullYear(), now.getMonth(), now.getDate()).toISOString()
      break
    }
    case 'last_24h': {
      start = new Date(now.getTime() - 24 * 60 * 60 * 1000).toISOString()
      end = now.toISOString()
      break
    }
    case 'this_week': {
      const dayOfWeek = now.getDay()
      const diff = now.getDate() - dayOfWeek + (dayOfWeek === 0 ? -6 : 1)
      start = new Date(now.getFullYear(), now.getMonth(), diff).toISOString()
      end = now.toISOString()
      break
    }
    default: {
      start = new Date(now.getTime() - 24 * 60 * 60 * 1000).toISOString()
      end = now.toISOString()
    }
  }

  return { start, end }
}

