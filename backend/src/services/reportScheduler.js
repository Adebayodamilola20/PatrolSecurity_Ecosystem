async function runAutoEmailCycle() {
  try {
    const settings = await db.all('SELECT * FROM communicationSettings')

    const enabled = getSettingValue(settings, 'auto_report_enabled', 'false')
    if (enabled !== 'true') return

    const scheduleType = getSettingValue(settings, 'auto_report_schedule', 'daily')
    const rangeType = getSettingValue(settings, 'auto_report_range', 'last_24h')
    const recipients = getSettingValue(settings, 'report_email_recipients', '')
      .split(',').map(v => v.trim()).filter(Boolean)

    if (recipients.length === 0) return

    const { start, end } = getDateRange(rangeType)

    const clientIds = await db.all('SELECT DISTINCT clientId FROM checkpoints WHERE clientId IS NOT NULL AND active = 1')

    for (const { clientId } of clientIds) {
      const client = await db.get('SELECT * FROM clients WHERE id = ?', [clientId])
      if (!client) continue

      const scans = await db.all(`
        SELECT s.*, u.name as officerName, c.name as checkpointName, c.code as checkpointCode
        FROM scans s
        JOIN users u ON s.officerId = u.id
        JOIN checkpoints c ON s.checkpointId = c.id
        WHERE s.scannedAt >= ? AND s.scannedAt <= ? AND c.clientId = ?
        ORDER BY s.scannedAt DESC
      `, [start, end, clientId])

      if (scans.length === 0) continue

      const shifts = await db.all(`
        SELECT s.*, u.name as userName FROM shifts s
        JOIN users u ON s.userId = u.id
        WHERE s.clockIn >= ? AND (s.clockOut IS NULL OR s.clockOut <= ?) AND u.clientId = ?
      `, [start, end, clientId])

      const totalHours = shifts.reduce((acc, s) => {
        if (!s.clockOut) return acc
        return acc + (new Date(s.clockOut).getTime() - new Date(s.clockIn).getTime())
      }, 0)

      const verified = scans.filter(s => s.gpsValid).length
      const flagged = scans.length - verified

      const reportData = {
        clientEmail: recipients.join(', '),
        periodStart: start,
        periodEnd: end,
        scans,
        verified,
        flagged,
        totalHours,
      }

      const html = buildReportHtml(reportData)

      const reportId = uuidv4()
      await db.run(`
        INSERT INTO reports (id, clientEmail, periodStart, periodEnd, format, status, sentAt)
        VALUES (?, ?, ?, ?, ?, ?, ?)
      `, [reportId, recipients.join(', '), start, end, 'html', 'sending', null])

      const result = await sendNotificationBundle({
        emails: recipients,
        subject: `Auto Patrol Report — ${new Date(start).toLocaleDateString()} to ${new Date(end).toLocaleDateString()}`,
        html,
        text: `Auto Patrol Report\nPeriod: ${start} — ${end}\nTotal scans: ${scans.length}\nVerified: ${verified}\nFlagged: ${flagged}\nPatrol hours: ${Math.round(totalHours / 3600000 * 10) / 10}h`,
      })

      await db.run(
        `UPDATE reports SET status = ?, sentAt = ? WHERE id = ?`,
        [result.skipped ? 'failed' : 'sent', result.skipped ? null : new Date().toISOString(), reportId]
      )
    }
  } catch (err) {
    console.error('[reportScheduler]', err.message)
  }
}

let intervalHandle = null

export function startReportScheduler(intervalMinutes = 60) {
  if (intervalHandle) return
  console.log(`[reportScheduler] Starting auto-email cycle every ${intervalMinutes} minutes`)
  runAutoEmailCycle()
  intervalHandle = setInterval(runAutoEmailCycle, intervalMinutes * 60 * 1000)
}

export function stopReportScheduler() {
  if (intervalHandle) {
    clearInterval(intervalHandle)
    intervalHandle = null
    console.log('[reportScheduler] Stopped')
  }
}
